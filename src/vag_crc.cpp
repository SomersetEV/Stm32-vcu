uint8_t VagCrc::Calc(uint8_t *bytes, uint8_t length, uint32_t id) {
  const uint8_t poly = 0x2F;
  const uint8_t xor_output = 0xFF;
  const uint8_t *magic = MagicBytes(id);
  // only the low nibble of the counter is relevant
  uint8_t magicByte = magic ? magic[bytes[1] & 0x0F] : 0x00;
  uint8_t crc = 0xFF;

  for (uint8_t i = 1; i < length + 1; i++) {
    // We skip the empty CRC position and start at the counter. The last
    // element is the VAG magic byte for the message depending on the counter.
    if (i < length)
      crc ^= bytes[i];
    else
      crc ^= magicByte;

    for (uint8_t j = 0; j < 8; j++) {
      if (crc & 0x80)
        crc = (crc << 1) ^ poly;
      else
        crc = (crc << 1);
    }
  }

  crc ^= xor_output;

  bytes[0] = crc; // set the CRC checksum directly in the output bytes
  return crc;
}
